#!/usr/bin/env python3
"""verify/contrast.py: every school palette must give readable text on primary buttons/bars
and readable bars against paper, and the school colour used as text or an outline (--primary-text:
links, focus rings, flashcard answers, chips, toggle and tab edges) must reach 4.5:1 on both papers of
both themes. Status colours (--ok, --bad, --warn) must reach 4.5:1 as chip text on their own tint in
both themes. Mirrors the swap/darken/lighten logic in assets/app.js and the tokens in assets/app.css.
Exit 1 on any failure. Writes docs/PALETTE_NOTES.md."""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
PAPER = "#FBF8F1"
PAPERS = {"light": ["#FBF8F1", "#F2EDE0"], "dark": ["#141A16", "#1C2520"]}
# Must match assets/app.css (:root light values, then the dark block).
STATUS = {"light": {"ok": "#176B41", "bad": "#A12A24", "warn": "#7F5600"},
          "dark": {"ok": "#5FD39A", "bad": "#FF8F85", "warn": "#E8B84A"}}

def rgb(h):
    h = h.lstrip("#")
    if len(h) == 3: h = "".join(c*2 for c in h)
    return tuple(int(h[i:i+2], 16) for i in (0, 2, 4))

def lum(c):
    def f(v):
        v /= 255
        return v/12.92 if v <= 0.03928 else ((v+0.055)/1.055)**2.4
    r, g, b = c
    return 0.2126*f(r)+0.7152*f(g)+0.0722*f(b)

def contrast(a, b):
    la, lb = lum(rgb(a)), lum(rgb(b))
    hi, lo = max(la, lb), min(la, lb)
    return (hi+0.05)/(lo+0.05)

def on_color(bg):
    return "#FFFFFF" if contrast(bg, "#FFFFFF") >= contrast(bg, "#1F1F1F") else "#1F1F1F"

def darken(h, amt):
    return "#%02x%02x%02x" % tuple(max(0, round(c*(1-amt))) for c in rgb(h))

def lighten(h, amt):
    return "#%02x%02x%02x" % tuple(min(255, round(c + (255-c)*amt)) for c in rgb(h))

def mix(fg, p, bg):
    a, b = rgb(fg), rgb(bg)
    return "#%02x%02x%02x" % tuple(round(a[i]*p + b[i]*(1-p)) for i in range(3))

def primary_text(primary, theme):
    """Same loop as app.js primaryText()."""
    c = primary
    for _ in range(60):
        if all(contrast(c, p) >= 4.5 for p in PAPERS[theme]): break
        c = lighten(c, 0.06) if theme == "dark" else darken(c, 0.06)
    return c

def check_css_tokens(fails):
    css = open(os.path.join(ROOT, "assets", "app.css"), encoding="utf-8").read().lower()
    for theme, cols in STATUS.items():
        for k, v in cols.items():
            if f"--{k}: {v.lower()}" not in css and f"--{k}:{v.lower()}" not in css:
                fails.append(f"app.css: --{k} {theme} value {v} not found (contrast.py STATUS is out of sync)")

def main():
    data = json.load(open(os.path.join(ROOT, "data", "schools.json")))
    fails, notes, results = [], [], []
    check_css_tokens(fails)
    status_rows = []
    for theme, cols in STATUS.items():
        for k, v in cols.items():
            # chip text on its 15% tint (12 to 15% across chips, feedback and choices), over either paper
            r = min(contrast(v, mix(v, pct, p)) for p in PAPERS[theme] for pct in (0.12, 0.14, 0.15))
            status_rows.append(f"| {theme} | --{k} | {v} | {r:.2f} |")
            if r < 4.5: fails.append(f"--{k} ({theme}) {v}: {r:.2f} on its tint (need 4.5)")
    for s in data["schools"]:
        c = s["colors"]; primary = c["primary"]; derived = []
        if contrast(primary, "#FFFFFF") < 2.5 and contrast(c["secondary"], "#FFFFFF") >= 2.5:
            primary = c["secondary"]; derived.append("primary swapped with secondary (near-white primary)")
        if contrast(primary, PAPER) < 3:
            primary = darken(primary, 0.35); derived.append(f"primary darkened to {primary} for bar contrast")
        oc = on_color(primary)
        steps = 0
        while contrast(primary, oc) < 4.5 and steps < 6:
            primary = darken(primary, 0.12); oc = on_color(primary); steps += 1
        if steps: derived.append(f"primary darkened {steps}x to {primary} for text contrast")
        text_ratio = contrast(primary, oc)
        bar_ratio = contrast(primary, PAPER)
        ok = text_ratio >= 4.5 and bar_ratio >= 3
        if not ok:
            fails.append(f"{s['id']}: text {text_ratio:.2f} (need 4.5), bar {bar_ratio:.2f} (need 3)")
        pt = {}
        for theme in ("light", "dark"):
            t = primary_text(primary, theme); r = min(contrast(t, p) for p in PAPERS[theme]); pt[theme] = (t, r)
            if r < 4.5: fails.append(f"{s['id']}: primary as text on {theme} paper {r:.2f} (need 4.5)")
        raw_dark = min(contrast(primary, p) for p in PAPERS["dark"])
        results.append((s["id"], primary, raw_dark, pt["light"], pt["dark"]))
        notes.append(f"| {s['name']} | {c['names']} | {c['primary']} | {primary} | {oc} | {text_ratio:.1f} | {bar_ratio:.1f} | {pt['light'][0]} {pt['light'][1]:.1f} | {pt['dark'][0]} {pt['dark'][1]:.1f} | {s['status']} | {'; '.join(derived) or ''} |")
    os.makedirs(os.path.join(ROOT, "docs"), exist_ok=True)
    with open(os.path.join(ROOT, "docs", "PALETTE_NOTES.md"), "w") as f:
        f.write("# Palette notes (generated by build_scripts/verify/contrast.py)\n\n")
        f.write("Status: INFERRED = color names from an official source (HHSAA), hex approximated. UNVERIFIED = names from secondary sources or not found; neutral Alakaʻi fallback used.\n\n")
        f.write("Primary as text (`--primary-text`) is the school colour darkened (light theme) or lightened (dark theme) until it reaches 4.5:1 on both papers of that theme (light #FBF8F1 and #F2EDE0, dark #141A16 and #1C2520); the ratio shown is the lower of the two.\n\n")
        f.write("| School | Names | Declared primary | Effective primary | Text on primary | Text ratio | Bar vs paper | Primary as text, light | Primary as text, dark | Status | Derivations |\n|---|---|---|---|---|---|---|---|---|---|---|\n")
        f.write("\n".join(notes) + "\n")
        f.write("\n## Status colours (chip text on its own tint, lower of both papers)\n\n| Theme | Token | Value | Ratio |\n|---|---|---|---|\n" + "\n".join(status_rows) + "\n")
    if fails:
        print("CONTRAST FAILURES:\n  " + "\n  ".join(fails)); sys.exit(1)
    if "-v" in sys.argv:
        for sid, prim, raw, lt, dk in results: print(f"  {sid:13} primary {prim} raw-on-dark {raw:.2f}  text light {lt[0]} {lt[1]:.2f}  text dark {dk[0]} {dk[1]:.2f}")
    print(f"contrast ok: {len(data['schools'])} schools x 2 themes (text 4.5:1 on both papers), status colours ok, notes written to docs/PALETTE_NOTES.md")

if __name__ == "__main__":
    main()
